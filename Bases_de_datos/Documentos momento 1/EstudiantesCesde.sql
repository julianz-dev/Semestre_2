-- 2. CREAR LAS TABLAS

CREATE TABLE Ciudades (
    IdCiudad INT IDENTITY(1,1) PRIMARY KEY,
    NombreCiudad NVARCHAR(60)
);

CREATE TABLE Sedes (
    IdSede INT IDENTITY(1,1) PRIMARY KEY,
    NombreSede NVARCHAR(100),
    Direccion NVARCHAR(150),
    Telefono VARCHAR(20),
    IdCiudad INT,
    FOREIGN KEY (IdCiudad) REFERENCES Ciudades(IdCiudad)
);

CREATE TABLE Generos (
    IdGenero INT IDENTITY(1,1) PRIMARY KEY,
    NombreGenero NVARCHAR(50)
);

CREATE TABLE Estudiantes (
    IdEstudiante INT IDENTITY(1,1) PRIMARY KEY,
    TipoDocumento VARCHAR(10),
    NumeroDocumento VARCHAR(20),
    Nombres NVARCHAR(100),
    Apellidos NVARCHAR(100),
    IdGenero INT,
    FechaNacimiento DATE,
    Telefono VARCHAR(20),
    Celular VARCHAR(20),
    Correo NVARCHAR(150),
    Direccion NVARCHAR(150),
    IdCiudad INT,
    IdSede INT,
    FechaIngreso DATE,
    Activo BIT,
    FOREIGN KEY (IdGenero) REFERENCES Generos(IdGenero),
    FOREIGN KEY (IdCiudad) REFERENCES Ciudades(IdCiudad),
    FOREIGN KEY (IdSede) REFERENCES Sedes(IdSede)
);

CREATE TABLE Profesores (
    IdProfesor INT IDENTITY(1,1) PRIMARY KEY,
    TipoDocumento VARCHAR(10),
    NumeroDocumento VARCHAR(20),
    Nombres NVARCHAR(100),
    Apellidos NVARCHAR(100),
    Telefono VARCHAR(20),
    Celular VARCHAR(20),
    Correo NVARCHAR(150),
    Especialidad NVARCHAR(120),
    Activo BIT
);

CREATE TABLE Niveles (
    IdNivel INT IDENTITY(1,1) PRIMARY KEY,
    NumeroNivel INT,
    NombreNivel NVARCHAR(50)
);

CREATE TABLE Materias (
    IdMateria INT IDENTITY(1,1) PRIMARY KEY,
    CodigoMateria VARCHAR(15),
    NombreMateria NVARCHAR(120),
    Creditos INT,
    HorasSemanales INT,
    IdNivel INT,
    FOREIGN KEY (IdNivel) REFERENCES Niveles(IdNivel)
);

CREATE TABLE Grupos (
    IdGrupo INT IDENTITY(1,1) PRIMARY KEY,
    CodigoGrupo VARCHAR(20),
    IdMateria INT,
    IdSede INT,
    CupoMaximo INT,
    FOREIGN KEY (IdMateria) REFERENCES Materias(IdMateria),
    FOREIGN KEY (IdSede) REFERENCES Sedes(IdSede)
);

CREATE TABLE ProfesoresGrupos (
    IdProfesorGrupo INT IDENTITY(1,1) PRIMARY KEY,
    IdProfesor INT,
    IdGrupo INT,
    FOREIGN KEY (IdProfesor) REFERENCES Profesores(IdProfesor),
    FOREIGN KEY (IdGrupo) REFERENCES Grupos(IdGrupo)
);

CREATE TABLE Matriculas (
    IdMatricula INT IDENTITY(1,1) PRIMARY KEY,
    IdEstudiante INT,
    IdGrupo INT,
    FechaMatricula DATE,
    Estado NVARCHAR(20),
    NotaFinal DECIMAL(3,2),
    FOREIGN KEY (IdEstudiante) REFERENCES Estudiantes(IdEstudiante),
    FOREIGN KEY (IdGrupo) REFERENCES Grupos(IdGrupo)
);
GO

